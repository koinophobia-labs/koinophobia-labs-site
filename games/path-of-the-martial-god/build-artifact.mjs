/**
 * Artifact build — a DISTRIBUTION ADAPTER, not a variant of the game.
 *
 * The repository implementation is canonical. This script produces `dist/` for
 * hosting and is allowed to change exactly two things, both forced by the sandbox:
 *
 *   1. JSON module -> JS module. `sim/techniques.js` imports the technique data with
 *      an import attribute (`with { type: 'json' }`). The hosted sandbox serves the
 *      page under a strict CSP where a JSON module request is not reliably permitted,
 *      so the same data is emitted as `low-river.data.js` exporting the identical
 *      object, and the one import line is rewritten. The script asserts the emitted
 *      object deep-equals the JSON before writing anything.
 *
 *   2. Page shape and import root. The host wraps the page in its own
 *      <!doctype>/<head>/<body>, so `index.html` is emitted as page content only,
 *      and `../view/main.js` becomes `./view/main.js` because the page sits at the
 *      artifact root rather than in `web/`.
 *
 * Nothing else is touched: no timings, no AI parameters, no structure behaviour, no
 * movement, no damage, no Final Inch logic, no input grammar. Every other file is
 * copied byte-for-byte, and `verify-parity.mjs` proves the built simulation produces
 * an identical fight.
 */
import { readFile, writeFile, mkdir, rm, copyFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import assert from 'node:assert/strict';

const ROOT = new URL('.', import.meta.url).pathname;
const DIST = join(ROOT, 'dist');

const COPY = [
  'sim/constants.js', 'sim/fighter.js', 'sim/fight.js', 'sim/finalInch.js',
  'sim/formMachine.js', 'sim/grammar.js', 'sim/replay.js', 'sim/resolve.js',
  'sim/structure.js', 'sim/ai/brain.js', 'sim/ai/perception.js',
  'view/audio.js', 'view/debug.js', 'view/input.js', 'view/main.js',
  'view/pose.js', 'view/render.js', 'view/survey.js', 'view/telemetry.js',
];

async function out(rel, text) {
  const p = join(DIST, rel);
  await mkdir(dirname(p), { recursive: true });
  await writeFile(p, text);
}

await rm(DIST, { recursive: true, force: true });
await mkdir(DIST, { recursive: true });

// ---- 1. technique data: JSON -> ES module, verified identical ------------------
const rawJson = await readFile(join(ROOT, 'sim/data/low-river.json'), 'utf8');
const data = JSON.parse(rawJson);
const moduleSrc =
  '// GENERATED by build-artifact.mjs from low-river.json — do not edit.\n' +
  '// Identical content; a module only because the hosted sandbox will not reliably\n' +
  '// serve a JSON module import.\n' +
  `export default ${JSON.stringify(data, null, 2)};\n`;
assert.deepEqual(
  JSON.parse(moduleSrc.slice(moduleSrc.indexOf('export default ') + 15, -2)),
  data,
  'generated technique module must deep-equal the canonical JSON',
);
await out('sim/data/low-river.data.js', moduleSrc);

// ---- 2. the one rewritten import ----------------------------------------------
const tech = await readFile(join(ROOT, 'sim/techniques.js'), 'utf8');
const FROM = "import lowRiver from './data/low-river.json' with { type: 'json' };";
const TO = "import lowRiver from './data/low-river.data.js';";
assert.ok(tech.includes(FROM), 'techniques.js import line not found — adapter is stale');
await out('sim/techniques.js', tech.replace(FROM, TO));

// ---- 3. everything else, byte-for-byte ----------------------------------------
for (const rel of COPY) {
  const p = join(DIST, rel);
  await mkdir(dirname(p), { recursive: true });
  await copyFile(join(ROOT, rel), p);
}

// ---- 4. the page, as content only ----------------------------------------------
const html = await readFile(join(ROOT, 'web/index.html'), 'utf8');
const title = html.match(/<title>([\s\S]*?)<\/title>/)[1];
const style = html.match(/<style>([\s\S]*?)<\/style>/)[1];
const body = html.match(/<body>([\s\S]*?)<\/body>/)[1].replace('../view/main.js', './view/main.js');
await out('index.html', `<title>${title}</title>\n<style>${style}</style>\n${body.trim()}\n`);

const files = [...COPY, 'sim/techniques.js', 'sim/data/low-river.data.js'];
console.log(`dist/ built: ${files.length} modules + index.html`);
console.log(files.map((f) => `  ${f}`).join('\n'));
